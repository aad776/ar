// Turns a Studio "Export backup" .json into static files bundled with the site,
// so /birthday/<slug> works on Vercel without Supabase.
//
//   node scripts/bake-backup.mjs <backup.json> [slug]
//
// Writes media to public/u/<slug>/ and the config to src/lib/baked/<slug>.json,
// then regenerates src/lib/baked/index.ts.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [, , file, slugArg] = process.argv;
if (!file) {
  console.error("usage: node scripts/bake-backup.mjs <backup.json> [slug]");
  process.exit(1);
}
const data = JSON.parse(readFileSync(file, "utf8"));
if (data?.kind !== "little-universe-backup" || !data.config) throw new Error("Not a Little Universe backup file");

const config = data.config;
const slug = (slugArg || config.recipientName || "birthday")
  .toLowerCase()
  .normalize("NFKD")
  .replace(/[^a-z0-9]+/g, "-")
  .replace(/^-+|-+$/g, "");
if (!/^[a-z0-9](?:[a-z0-9-]{1,62}[a-z0-9])$/.test(slug) || slug === "demo") throw new Error(`Bad slug: ${slug}`);

const root = process.cwd();
const mediaDir = join(root, "public", "u", slug);
const bakedDir = join(root, "src", "lib", "baked");
mkdirSync(mediaDir, { recursive: true });
mkdirSync(bakedDir, { recursive: true });

const EXT = {
  "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp", "image/gif": "gif", "image/avif": "avif",
  "video/mp4": "mp4", "video/webm": "webm", "video/quicktime": "mov",
  "audio/mpeg": "mp3", "audio/mp4": "m4a", "audio/aac": "aac", "audio/wav": "wav", "audio/x-wav": "wav",
  "audio/ogg": "ogg", "audio/webm": "weba",
};

const written = {};
let bytes = 0;
for (const [key, dataUrl] of Object.entries(data.files ?? {})) {
  if (!/^[a-z0-9-]+$/i.test(key)) continue;
  const m = /^data:([^;,]+)?(;base64)?,(.*)$/s.exec(dataUrl);
  if (!m) continue;
  const mime = (m[1] || "application/octet-stream").toLowerCase();
  const buf = m[2] ? Buffer.from(m[3], "base64") : Buffer.from(decodeURIComponent(m[3]));
  const name = `${key}.${EXT[mime] ?? "bin"}`;
  writeFileSync(join(mediaDir, name), buf);
  written[key] = `/u/${slug}/${name}`;
  bytes += buf.length;
}

const fix = (s) => (s?.startsWith("idb:") ? written[s.slice(4)] : s);
let missing = 0;
for (const a of Object.values(config.assets ?? {})) {
  a.src = fix(a.src);
  if (a.poster) a.poster = fix(a.poster);
  if (!a.src) missing++;
}

writeFileSync(join(bakedDir, `${slug}.json`), JSON.stringify(config, null, 2));

const slugs = readdirSync(bakedDir).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5));
writeFileSync(
  join(bakedDir, "index.ts"),
  `// Generated by scripts/bake-backup.mjs - do not edit by hand.\n` +
    slugs.map((s, i) => `import c${i} from "./${s}.json";`).join("\n") +
    `\n\nexport const bakedExperiences: Record<string, unknown> = {\n` +
    slugs.map((s, i) => `  ${JSON.stringify(s)}: c${i},`).join("\n") +
    `\n};\n`
);

console.log(`Baked "${slug}": ${Object.keys(written).length} files, ${(bytes / 1e6).toFixed(1)} MB`);
if (missing) console.warn(`Warning: ${missing} asset(s) had no file in the backup`);
console.log(`Page: /birthday/${slug}`);
